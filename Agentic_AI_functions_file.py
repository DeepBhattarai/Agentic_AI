# This is the main orcherstrator agent which routes the question to appropriate agent based on the category of the questions.

def Agentic_AI_orchestrator(user_prompt: str,db_path: str,model: str):
  question = user_prompt
  routing_prompt = f""" You are a routing agent who analyzes the user {question} and determine the next step in this workflow.
                    Analyze the user's question and categorize it.

                   EXAMPLES:
                  User: 'What is the temperature in London?'
                  Response: CATEGORY: WEATHER | SUBJECT: London

                  User: 'Show me the top 5 customers by sales.'
                  Response: CATEGORY: SQL | SUBJECT: None

                  User: 'Give the most expensive product sold.'
                  Response: CATEGORY: SQL | SUBJECT: None

                  User: 'Is it going to rain today in London?'
                  Response: CATEGORY:wikipedia_search | SUBJECT: London

                  User: 'How are you today?'
                  Response: CATEGORY: OTHER | SUBJECT: None

                  User: 'What is deep learning?'
                  Response: CATEGORY: OTHER | SUBJECT: None


              User: "{question}"
              Response:
              Do not respond with anything else.
                    """
  print(f'Please wait thinking for better response .....')
  routing_response = client.chat.completions.create(
      model = model,

      messages = [
          {"role": "system", "content": "You are a concise assistant. If asked a yes/no question, answer only with Yes or No followed by a short reason."},
          {'role':'user','content':routing_prompt}],
      temperature = 1.0
  )
  got_response = routing_response.choices[0].message.content.strip()
  #print(got_response)
  #print(f'Please wait thinking for better response: ')
  try:
    if 'WEATHER' in got_response:
      city_name = got_response.split('SUBJECT:')[-1].strip()

      return get_temperature(city_name=city_name,model=model)
    elif 'SQL' in got_response:
      return sql_agent_work_flow(question,db_path,model)
    elif 'OTHER' in got_response:
        general_response = client.chat.completions.create(
            model=model,
            messages=[{"role": "user", "content": question}]
            )
        return general_response.choices[0].message.content.strip()
    else:
      return f'I cannot answer this question'

  except Exception as e:
    return f"Error has occured: {e}"

