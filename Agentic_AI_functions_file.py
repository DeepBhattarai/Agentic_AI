# instantiates the client
client = ai.Client()

# function gets the schema of the sales table from SQLite database
def get_schema(db_path : str)-> str:
  """
  Return the 'sales' table schema that need to use by agent.

  """
  con = sqlite3.connect(db_path)
  cur = con.cursor()
  cur.execute("PRAGMA table_info(sales)")
  rows = cur.fetchall()
  con.close()
  return ("Table name: sales\n"
          +"\n".join([f"{r[1]} ({r[2]})" for r in rows])
  )
