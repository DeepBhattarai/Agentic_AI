# function executes the SQL query and return the result as a pandas DataFrame
def execute_query(query: str,db_path: str):
  """
  Execute any SELECT over the 'sales' table.
  Return the result as a pandas DataFrame.
  """
  edited_query = (
      query.replace("```sql","")
      .replace("```","")
      .strip()
      )  #.removeprefix("```sql").removesuffix("```")
  print(edited_query)
  con = sqlite3.connect(db_path)
  try:
    return pd.read_sql_query(edited_query,con)
  except Exception as e:
    return pd.DataFrame({"error" : [str(e)]})
  finally:
    con.close()

# function gets the weather information for a given city using OpenWeatherMap API

def get_weather(city_name: str):
    weather_api_key = os.environ.get("WEATHER_API_KEY")
    # It's better to pass the API key as an argument or use an environment variable
    url = f"https://api.openweathermap.org/data/2.5/weather?q={city_name}&appid={weather_api_key}"

    try:
        # 1. Execute the request
        response = requests.get(url)

        # 2. Check if the HTTP request itself failed (e.g., 404 or 401)
        response.raise_for_status()

        # 3. Parse the data
        data = response.json()

        # Extract info safely
        degree_celsius = round(data['main']['temp'] - 273.15)
        weather = data['weather'][0]['main']
        description = data['weather'][0]['description']
        feels_like_temp = round(data['main']['feels_like'] - 273.15)

        # 4. Return a plain string (which is JSON serializable)
        return (
            f"The current temperature of {city_name} is {degree_celsius}°C. "
            f"The weather is {weather} with {description}. "
            f"It feels like {feels_like_temp}°C."
        )

    except Exception as e:
        return f"Error: Could not retrieve weather for {city_name}. Details: {str(e)}"

# Agent will call this function and grabs weather information for the city.

def get_temperature(city_name: str,model: str) -> str:
  #city_name = input("Enter the city name: ").strip()
  Prompt = f""" You are a weather agent who gets the weather for the {city_name} asked by the user."""
  messages = [
    {"role": "system","content": "Always respond in british english."},
    {"role": "user","content": Prompt}
  ]
  response = client.chat.completions.create(
      model=model,
      messages=messages,
      tools=[get_weather],
      max_turns = 3,
      temperature = 1.0
  )

  return response.choices[0].message.content

# function generates SQL query based on user question and database schema using LLM

def sql_generator(question: str,schema: str,model: str,db_path: str) -> str:

    Prompt = f""" You are a SQL helper. Given the schema of the database table 'sales' and question, respond with SQL query only to answer it.

    Schema =
    {schema}

    User Question =
    {question}

    """
    response = client.chat.completions.create(
        model = model,
        messages = [{'role':'user','content': Prompt}],
        temperature = 1.0

    )
    return response.choices[0].message.content.strip()

# this agent reviews the initial sql query generated by sql_generator and provides feedback including improved query if required.
def sql_reviewer(
    question: str,
    schema: str,
    query_response: str,
    model: str,
    db_path: str
) -> tuple[str,str]:
    Prompt = f""" You are a sql reviewer. Given the schema of the database table 'sales',question and Initial query response,
    review the initial query and provide feedback on the query. If it needs improvement to answer user question provide improved query
    otherwise return the same query.
    Returns (feedback,improved_query).
    schema =
    {schema}
    User Question =
    {question}
    Initial Query Response =
    {query_response}

    Return STRICT JSON with two fields:
    {{
    "feedback": "<1-3 sentences explaining the gap or confirming correctness>",
    "reviewed_sql": "<final SQL to run>"
    }}
    """
    response = client.chat.completions.create(
        model = model,
        messages= [{'role':'user','content':Prompt}],
        temperature = 1.0
    )
    #print(response.choices[0].message.content.strip())

    reviewed_sql = response.choices[0].message.content.strip()

    try:
      reply = json.loads(reviewed_sql)
      feedback = reply['feedback']
      improved_query = reply['reviewed_sql']
      #print(f'Feedback: {feedback}')
      #print(f'Improved Query: {improved_query}')
    except Exception:
      Feedback: {reviewed_sql.strip()}
      reviewed_sql.strip() == query_response

    return feedback,improved_query

